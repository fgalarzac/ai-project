"""Restore this paper in a fresh, pinned AppliedModelingLib Linux checkout.

This restores exact files; it does not issue semantic judgments or acceptance.
The official paper-scoped checker must run afterward.
"""
from pathlib import Path
import argparse
import hashlib
import json
import shutil
import subprocess


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def require_hash(path, expected):
    actual = digest(path)
    if actual != expected:
        raise ValueError(f"SHA256 differs for {path}: expected {expected}, got {actual}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--aml', type=Path, required=True,
                        help='Fresh AppliedModelingLib checkout at the supplied registration commit')
    args = parser.parse_args()
    repo = Path(__file__).resolve().parents[1]
    aml = args.aml.resolve(strict=True)
    if not (aml / 'scripts' / 'paper_contribution.py').is_file() or not (aml / 'lean-toolchain').is_file():
        raise ValueError('--aml must name the AppliedModelingLib repository root')
    expected_head = '4d30604f45ddd6848fd87691c8e3ca63881b073b'
    head = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=aml, text=True).strip()
    if head != expected_head:
        raise ValueError(f'Use the exact registration checkout {expected_head}; found {head}')
    paper_id = 'Galarza26RelativeCredit'
    target = aml / 'papers' / paper_id
    entrypoint = aml / 'papers' / f'{paper_id}.lean'
    if target.exists() or entrypoint.exists():
        raise FileExistsError('Use a fresh checkout; an existing paper will not be overwritten')
    evidence = repo / 'docs' / 'lean_evidence'
    pin = json.loads((evidence / 'source_pin.json').read_text(encoding='utf-8'))
    public_artifacts = json.loads((evidence / 'public_artifacts.json').read_text(encoding='utf-8'))
    def source_path(key, default):
        path = (repo / pin.get(key, default)).resolve(strict=True)
        if not path.is_relative_to(repo):
            raise ValueError('Pinned source must remain inside the project')
        return path
    source_pdf = source_path('repo_pdf_path', 'paper/paper.pdf')
    source_tex = source_path('repo_tex_path', 'paper/paper.tex')
    require_hash(source_pdf, pin['pdf_sha256'])
    require_hash(source_tex, pin['tex_sha256'])
    for relative, expected in public_artifacts['sha256'].items():
        path = (repo / relative).resolve(strict=True)
        if not path.is_relative_to(repo):
            raise ValueError('Artifact path must remain inside the project')
        require_hash(path, expected)
    shutil.copytree(repo / 'lean', target)
    shutil.copy2(evidence / f'{paper_id}.lean', entrypoint)
    shutil.copy2(source_pdf, target / 'source.pdf')
    shutil.copy2(source_tex, target / 'source.tex')
    # The course asks us to preserve the generated ignore file. Restore the
    # ignored packet from its separately published, byte-identical copy.
    shutil.copy2(evidence / 'HUMAN_REVIEW_PACKET.pdf', target / 'docs' / 'HUMAN_REVIEW_PACKET.pdf')
    text = target / 'source.txt'
    if not text.exists():
        subprocess.run(['pdftotext', str(target / 'source.pdf'), str(text)], check=True)
    require_hash(text, pin['text_sha256'])
    # Preserve the generated bytes, including the few CRLF metadata files.
    # Git's CR-at-EOL rule affects whitespace diagnostics only, not Lean or
    # source/evidence hashing. Keep this checkout setting outside the engine.
    info = aml / '.git' / 'info' / 'attributes'
    info.parent.mkdir(parents=True, exist_ok=True)
    with info.open('a', encoding='utf-8', newline='\n') as handle:
        handle.write(f'\npapers/{paper_id}/** -text whitespace=cr-at-eol\n')
        handle.write(f'papers/{paper_id}.lean -text\n')
    subprocess.run(['git', 'add', '--', f'papers/{paper_id}', f'papers/{paper_id}.lean'],
                   cwd=aml, check=True)
    print(f'Restored {paper_id} from paper commit {pin["source_commit"]}.')
    if digest(repo / 'paper' / 'paper.pdf') != pin['pdf_sha256']:
        print('This reproduces the accepted historical source. The current editorial edition is a different PDF; consult docs/lean_progreso.md for its validation status.')
    print('Exact source and public-artifact hashes match. Run the official fast check, module checkpoint, and receipt check.')


if __name__ == '__main__':
    main()
